lessons = []
cur = None
step = None

def lesson(n, en, fa):
    global cur
    cur = {"n": n, "en": en, "fa": fa, "rows": []}
    lessons.append(cur)

def S(name):
    global step
    step = name

def row(kind, t, play="", mean="", ans=""):
    cur["rows"].append((step, kind, t, play, mean, ans))

def L(t, play, mean): row("line", t, play, mean)
def D(t, play, mean, ans=""): row("drill", t, play, mean, ans)
def C(t, play, mean): row("command", t, play, mean)
def K(t, play, mean): row("check", t, play, mean)
def N(t, play="", mean=""): row("note", t, play, mean)
def T(t): row("tune", t)

